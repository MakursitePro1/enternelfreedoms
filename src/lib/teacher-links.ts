/** Readable name in the URL; the short immutable ID keeps equal names unique. */
export function teacherPath(item: Pick<InstitutionItem, 'id' | 'title'>) {
  const name = Array.from(item.title.trim().toLowerCase()).map((c) => letters[c] ?? c).join('')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 70).replace(/-$/g, '');
  return `${name || 'teacher'}-${item.id.slice(0, 8)}`;
}